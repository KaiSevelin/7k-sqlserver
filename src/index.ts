/**
 * A SQL Server provider for 7K.
 *
 * Its own repository, because D48 puts implementations outside the language: 7K states what the data is
 * and this says whether SQL Server can hold it.
 *
 * **Only the Data layer is here, and that is not a limitation — it is the whole of what is true.** A
 * message, a record, a value and an enum are *data*, and a table is what data lives in. A pipe is not a
 * table: it is a queue with a delivery guarantee, and generating a table called `Commands` with a
 * `Handled` flag would be inventing a transport the model never described. A service is not a table
 * either. A saga's state is closer — it genuinely is a row — but a saga is the Process layer and
 * belongs to whatever runs it.
 *
 * **What the tables are for is an archive.** One table per message, so that what flowed through the
 * system can be queried in the shape the model declared it, with the model's own rules enforced by the
 * thing holding the data rather than by whichever service remembered to. That is the one kind of
 * validation nobody can skip.
 *
 * **SQL expresses one thing a schema projection cannot, and misses two it can.** A `CHECK` sees the
 * whole row, so an invariant relating two fields of a message becomes a real constraint. A `pattern`
 * cannot be expressed at all, because SQL Server has no regular expression operator, and neither can a
 * `size` on a list, whose elements are rows in another table. Both are declared losses.
 *
 * **This generates the shape, not the migration.** The DDL is what the model implies now; turning an
 * existing database into it needs to know what is deployed, which no model can say. Running it twice is
 * safe, and that is as far as it goes.
 */

