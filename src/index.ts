const HEADER = [
  "-- <auto-generated>",
  "--   Generated from a 7K model. Do not edit: this file is owned by the generator and is replaced",
  "--   wholesale on the next run. Write what the model does not describe beside it, not inside it.",
  "--",
  "--   This is the shape the model implies, not a migration: turning an existing database into it",
  "--   needs to know what is deployed, which no model can say.",
  "-- </auto-generated>",
];

const indent = (lines: readonly string[]): string[] => lines.map((l) => (l === "" ? "" : `    ${l}`));

/** Wraps prose so a comment stays readable in a narrow pane. */
function wrap(text: string, width = 104): string[] {
  const out: string[] = [];
  let line = "";
  for (const word of text.split(/\s+/).filter((w) => w !== "")) {
    if (line !== "" && `${line} ${word}`.length > width) {
      out.push(line);
      line = word;
    } else {
      line = line === "" ? word : `${line} ${word}`;
    }
  }
  if (line !== "") out.push(line);
  return out;
}

const comment = (text: string): string[] => wrap(text).map((l) => `-- ${l}`);

/** One table, as the statements that create it. */
function createTable(table: Table, options: { drop: boolean; checks: boolean }): string[] {
  const ref = tableRef(table.schema, table.name);
  const lines: string[] = [];

  lines.push(
    ...comment(`\`${table.describes}\`.`),
    ...table.columns
      .filter((c) => c.note !== undefined)
      .flatMap((c) => comment(`${c.name} is nullable: ${c.note!}`)),
  );

  if (options.drop) {
    lines.push(`IF OBJECT_ID(N'${ref}', N'U') IS NOT NULL DROP TABLE ${ref};`, "GO", "");
  }

  const definitions = table.columns.map(
    (column) => `${bracket(column.name)} ${column.type} ${column.nullable ? "NULL" : "NOT NULL"},`,
  );

  const constraints: string[] = [
    `CONSTRAINT ${bracket(constraintName("PK", table.name, [], "pascal"))} PRIMARY KEY (` +
      `${table.primaryKey.map(bracket).join(", ")}),`,
  ];

  for (const unique of table.uniques) {
    constraints.push(
      `CONSTRAINT ${bracket(unique.name)} UNIQUE (${unique.columns.map(bracket).join(", ")}),`,
    );
  }

  if (table.foreignKey !== undefined) {
    const fk = table.foreignKey;
    constraints.push(
      `CONSTRAINT ${bracket(fk.name)} FOREIGN KEY (${fk.columns.map(bracket).join(", ")})`,
      `    REFERENCES ${fk.references} (${fk.referencedColumns.map(bracket).join(", ")})`,
      // A message is one value: deleting it takes its elements with it, because an orphaned line of
      // an order that no longer exists is not a thing the model can describe.
      "    ON DELETE CASCADE,",
    );
  }

  if (options.checks) {
    for (const check of table.checks) {
      constraints.push(...comment(check.what).map((c) => `${c}`));
      constraints.push(`CONSTRAINT ${bracket(check.name)} CHECK (${check.sql}),`);
    }
  }

  // The last entry carries no comma, which T-SQL insists on.
  const body = [...definitions, ...constraints];
  const lastReal = body.map((l, i) => (l.trimStart().startsWith("--") ? -1 : i)).reduce((a, b) => Math.max(a, b), -1);
  const trimmed = body.map((l, i) => (i === lastReal ? l.replace(/,$/, "") : l));

  lines.push(
    `IF OBJECT_ID(N'${ref}', N'U') IS NULL`,
    "BEGIN",
    ...indent([`CREATE TABLE ${ref} (`, ...indent(trimmed), ");"]),
    "END;",
    "GO",
  );

  for (const index of table.indexes) {
    lines.push(
      "",
      ...comment(index.why),
      `IF NOT EXISTS (SELECT 1 FROM sys.indexes WHERE name = N'${index.name}'`,
      `               AND object_id = OBJECT_ID(N'${ref}'))`,
      `    CREATE INDEX ${bracket(index.name)} ON ${ref} (${index.columns.map(bracket).join(", ")});`,
      "GO",
    );
  }

  return lines;
}

/** The schemas the script needs, created once and guarded. */
function createSchemas(schemas: readonly string[]): string[] {
  return schemas.flatMap((schema) =>
    schema === "dbo"
      ? []
      : [
          `IF SCHEMA_ID(N'${schema}') IS NULL EXEC(N'CREATE SCHEMA ${bracket(schema)};');`,
          "GO",
          "",
        ],
  );
}

export const sqlserver: Provider = {
  name: "sqlserver",
  target: "SQL Server 2016+ (T-SQL)",
  layouts: ["per-declaration", "per-package", "single"],
  options: OPTIONS,

  generate(request: Request): Generated {
    const schemaOption = String(request.options["schema"] ?? "");
    const casing: Casing = request.options["casing"] === "snake" ? "snake" : "pascal";
    const idColumn = String(request.options["idColumn"] ?? "messageId");
    const drop = request.options["drop"] === true;
    const collation = String(request.options["collation"] ?? "");

    const built: {
      decl: Decl;
      tables: readonly Table[];
      losses: readonly Loss[];
      checks: boolean;
    }[] = [];
    const refusals: Refusal[] = [];

    for (const decl of request.selected) {
      const options = request.optionsFor(decl);

      // A message is always a table. A record only where it is asked for: it is part of a message's
      // value and flattens into it, so a table of its own duplicates what is already there.
      const wanted =
        decl.kind === "message" || (decl.kind === "record" && options["records"] === true);
      if (!wanted) continue;

      const ctx: Context = { model: request.model, pkg: decl.id.pkg, collation };
      const schema = schemaFor(decl.id.pkg, schemaOption, casing);

      const result = tablesFor(decl as MessageIr | RecordIr, ctx, {
        casing,
        schema,
        idColumn,
      });

      if (result.problems.length > 0) {
        for (const problem of result.problems) {
          refusals.push({
            at: qnameOf(decl),
            declared: problem.declared,
            because: problem.because,
            draft: [
              {
                path: pathFor(decl, request.layout, casing),
                content: `${[
                  ...HEADER,
                  "",
                  ...comment(
                    `7K: ${problem.at} declares ${problem.declared}. ${problem.because}`,
                  ),
                  // A deliberate syntax error, so a forgiving run cannot be mistaken for a finished
                  // one: this script does not run, and says why on the line that stops it.
                  `RAISERROR (N'7K: ${problem.at} cannot be held by this provider.', 20, 1) WITH LOG;`,
                  "GO",
                ].join("\n")}\n`,
                losses: [],
                from: [qnameOf(decl)],
              },
            ],
          });
        }
        continue;
      }

      built.push({
        decl,
        tables: result.tables,
        losses: [
          ...result.losses,
          // Said once per declaration, because it is a property of every string in it.
          ...(collation === ""
            ? [
                {
                  construct: "string equality",
                  at: qnameOf(decl),
                  fidelity: "partial" as const,
                  detail:
                    `Text columns take the database's own collation. 7K compares strings exactly, so ` +
                    `where that collation is case- or accent-insensitive an enum accepts a member the ` +
                    `model never declared, a \`unique\` list calls two distinct elements duplicates, ` +
                    `and an invariant comparing two strings can hold where 7K says it does not.`,
                },
              ]
            : []),
        ],
        checks: options["checks"] !== false,
      });
    }

    return { artifacts: group(built, request.layout, casing, drop), refusals };
  },
};

const pathFor = (decl: Decl, layout: Request["layout"], casing: Casing): string => {
  if (layout === "single") return "schema.sql";
  if (layout === "per-package") return `${cased(decl.id.pkg === "" ? "dbo" : decl.id.pkg, casing)}.sql`;
  return `${cased(decl.id.pkg === "" ? "dbo" : decl.id.pkg, casing)}/${cased(decl.id.name, casing)}.sql`;
};

/**
 * Groups the tables into scripts.
 *
 * A parent table has to exist before the child that references it, which is why a table carries its
 * depth: within one file the order is by depth, and across files `per-declaration` keeps a message and
 * its children together so that one file is always runnable on its own.
 */
function group(
  built: readonly {
    decl: Decl;
    tables: readonly Table[];
    losses: readonly Loss[];
    checks: boolean;
  }[],
  layout: Request["layout"],
  casing: Casing,
  drop: boolean,
): Artifact[] {
  const script = (
    entries: readonly (typeof built)[number][],
    schemas: readonly string[],
  ): string => {
    const statements = entries.flatMap((entry) =>
      [...entry.tables]
        .sort((a, b) => a.depth - b.depth)
        .flatMap((table) => [...createTable(table, { drop, checks: entry.checks }), ""]),
    );
    return `${[...HEADER, "", ...createSchemas(schemas), ...statements].join("\n").trimEnd()}\n`;
  };

  const schemasOf = (entries: readonly (typeof built)[number][]): string[] => [
    ...new Set(entries.flatMap((e) => e.tables.map((t) => t.schema))),
  ].sort();

  if (layout === "per-declaration") {
    return built.map((entry) => ({
      path: pathFor(entry.decl, layout, casing),
      content: script([entry], schemasOf([entry])),
      losses: entry.losses,
      from: [qnameOf(entry.decl)],
    }));
  }

  if (layout === "per-package") {
    const byPackage = new Map<string, (typeof built)[number][]>();
    for (const entry of built) {
      const key = entry.decl.id.pkg;
      byPackage.set(key, [...(byPackage.get(key) ?? []), entry]);
    }
    return [...byPackage]
      .sort((a, b) => a[0].localeCompare(b[0]))
      .map(([, entries]) => ({
        path: pathFor(entries[0]!.decl, layout, casing),
        content: script(entries, schemasOf(entries)),
        losses: entries.flatMap((e) => e.losses),
        from: entries.map((e) => qnameOf(e.decl)),
      }));
  }

  return [
    {
      path: "schema.sql",
      content: script(built, schemasOf(built)),
      losses: built.flatMap((e) => e.losses),
      from: built.map((e) => qnameOf(e.decl)),
    },
  ];
}

export default sqlserver;
